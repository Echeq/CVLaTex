def t(key, lang=None):
    """Return the message `key` in `lang`.

    When `lang` is None the current UI language comes from prefs
    (ui_language, English by default). Resolution order: the requested
    language, then English, then Spanish. An unknown key returns the key
    itself, so no message is ever lost.
    """
    if lang is None:
        lang = prefs.get("ui_language")
    idioma = str(lang or DEFAULT_LANGUAGE).strip().lower()
    textos = MESSAGES.get(idioma) or {}
    if key in textos:
        return textos[key]
    if key in MESSAGES[DEFAULT_LANGUAGE]:
        return MESSAGES[DEFAULT_LANGUAGE][key]
    return MESSAGES["es"].get(key, key)
