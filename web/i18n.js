let currentLang = "en";

function t(key) {
  const table = I18N[currentLang] || I18N.en;
  return table[key] ?? I18N.en[key] ?? key;
}

function setLang(code) {
  currentLang = Object.prototype.hasOwnProperty.call(I18N, code) ? code : "en";
}

function getLang() {
  return currentLang;
}

function optionLabel(kind, value, lang) {
  const tables = OPTION_LABELS[kind] || {};
  const table = tables[lang || currentLang] || tables.en || {};
  const text = value == null ? "" : String(value);
  return Object.prototype.hasOwnProperty.call(table, text) ? table[text] : text;
}

function applyI18n(root = document) {
  const scope = root || document;
  document.documentElement.lang = currentLang;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  scope.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
}
